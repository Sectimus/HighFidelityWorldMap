"""Emit MinimapTiles.lua: zone maps drawn from the client's own tiles.

Instead of shipping stitched/re-encoded BLPs, record where each source
minimap tile lands in the zone's art layer and let the addon
``SetTexture(fdid)`` the client's own copy.

The placement maths is the generator's own (``_effective_tile_px``,
``compute_crop_box``, and the paste-rect clamping in ``process_zone``), so the
result lines up with the shipped BLP art pixel for pixel.  Reads the cached
``minimap_db.json`` and the minimap tile cache; no network.

    python3 scripts/emit_minimap_tiles.py            # all Type=Zone maps
    python3 scripts/emit_minimap_tiles.py Durotar    # just those folders
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from hfwm.config.tiles import UI_MAP_TYPE_ZONE  # noqa: E402
from hfwm.geometry.coordinates import compute_crop_box  # noqa: E402
from hfwm.pipeline.zone import _effective_tile_px  # noqa: E402

CACHE = next(ROOT.glob(".cache-*"))
OUT = ROOT.parents[0] / "addon" / "client" / "data" / "MinimapTiles.lua"

# Underground capitals: their minimap tiles are the mountain above, not the
# city. Left out; the city's own art is drawn from SubMaps.lua instead
# (scripts/emit_indoors.py SUBMAPS).
UNDERGROUND_SUBMAPS = {1455, 1458}  # Ironforge, Undercity


def place_region(region, layer_w, layer_h, have):
    """Mirror process_zone()'s per-region geometry; return a Lua-ready dict."""
    dx0 = max(0, min(int(round(region["ui_min_x"] * layer_w)), layer_w))
    dx1 = max(0, min(int(round(region["ui_max_x"] * layer_w)), layer_w))
    dy0 = max(0, min(int(round(region["ui_min_y"] * layer_h)), layer_h))
    dy1 = max(0, min(int(round(region["ui_max_y"] * layer_h)), layer_h))
    if dx1 - dx0 < 1 or dy1 - dy0 < 1:
        return None

    tp = _effective_tile_px(region, dx1 - dx0, dy1 - dy0)
    c0, r0 = region["col_min"], region["row_min"]
    scols = region["col_max"] - c0 + 1
    srows = region["row_max"] - r0 + 1
    box, cov = compute_crop_box(
        r0, c0, region["loc_top"], region["loc_bottom"],
        region["loc_left"], region["loc_right"], scols * tp, srows * tp, tp,
    )
    cw, ch = box[2] - box[0], box[3] - box[1]
    if cw < 1 or ch < 1:
        return None

    rect_w, rect_h = dx1 - dx0, dy1 - dy0
    px0 = max(0, dx0 + int(round(cov[0] * rect_w)))
    px1 = min(layer_w, dx0 + int(round(cov[2] * rect_w)))
    py0 = max(0, dy0 + int(round(cov[1] * rect_h)))
    py1 = min(layer_h, dy0 + int(round(cov[3] * rect_h)))
    if px1 - px0 < 1 or py1 - py0 < 1:
        return None

    sx, sy = (px1 - px0) / cw, (py1 - py0) / ch
    grid = []
    for r in range(r0, r0 + srows):
        for c in range(c0, c0 + scols):
            fdid = region["tiles"].get(f"{r}_{c}", 0)
            grid.append(fdid if fdid in have else 0)
    if not any(grid):
        return None
    return {
        "ox": px0 - box[0] * sx, "oy": py0 - box[1] * sy,
        "tw": tp * sx, "th": tp * sy,
        "cols": scols, "rows": srows, "f": grid,
    }


def lua_region(g):
    f = ",".join(str(v) for v in g["f"])
    return (f"{{ox={g['ox']:.3f},oy={g['oy']:.3f},tw={g['tw']:.4f},"
            f"th={g['th']:.4f},cols={g['cols']},rows={g['rows']},f={{{f}}}}}")


def main(only):
    db = json.loads((CACHE / "minimap_db.json").read_text())
    have = {int(p.stem) for p in (CACHE / "minimap").glob("*.blp")}
    lines = ["-- Auto-generated by scripts/emit_minimap_tiles.py - DO NOT EDIT",
             "-- Zone maps as placements of the client's own minimap tiles.",
             "HFWMF_MINIMAP_ZONES = {"]
    zones = 0
    for folder, z in sorted(db.items()):
        if (z["ui_map_type"] != UI_MAP_TYPE_ZONE or (only and folder not in only)
                or z["ui_map_id"] in UNDERGROUND_SUBMAPS):
            continue
        # Small zones (cities) have no `native` grid: Blizzard's layer is
        # already as sharp as their minimap source.
        geo = z.get("native") or z
        regions = [g for g in (place_region(r, geo["layer_w"], geo["layer_h"], have)
                               for r in z["regions"]) if g]
        if not regions:
            continue
        zones += 1
        body = ",".join(lua_region(g) for g in regions)
        lines.append(f"    [{z['ui_map_id']}] = {{layerW={geo['layer_w']},"
                     f"layerH={geo['layer_h']},regions={{{body}}}}},  -- {folder}")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{zones} zones -> {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main(set(sys.argv[1:]))
